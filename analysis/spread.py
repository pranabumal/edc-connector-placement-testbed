"""
spread.py — the whole spread of per-message times, not only the median (feedback of
K. Mätäsniemi, 29 Oct 2026: the median hides the transfers that took far longer).

  Push  Set A, request to received, three runs per placement, warm-up excluded
        (the same values as rq1.py: analysis/out/rq1.json, key "push").
  Pull  Set B, fetch time with one worker, all three runs per placement
        (protocol run + repeats, as repeats_BD.py), warm-up excluded;
        the baseline without EDC from the same runs.

Writes the thesis table T5_spread (min, median, 95th percentile, max) to
analysis/out/tables/ and the numbers to analysis/out/spread.json.
Run after rq1.py, from the repository root:  analysis/.venv/bin/python analysis/spread.py
"""
import json

import numpy as np

from common import OUT, PLACEMENTS, TCS, write_numbers, write_table
from repeats_BD import fetch_ms, runs_B

NAME = {"hybrid": "Hybrid", "edge": "Edge", "cloud": "Cloud"}
TCN = {"tc1": "TC1", "tc2": "TC2", "tc3": "TC3"}


def stats(v):
    v = np.asarray(v, float)
    return {"n": int(len(v)), "min": float(v.min()), "median": float(np.median(v)),
            "q1": float(np.percentile(v, 25)), "q3": float(np.percentile(v, 75)),
            "p95": float(np.percentile(v, 95)), "p99": float(np.percentile(v, 99)), "max": float(v.max())}


push = json.loads((OUT / "rq1.json").read_text())["push"]
N = {"push": {}, "pull": {}, "baseline": {}}
for tc in TCS:
    for k in N:
        N[k][tc] = {}
    for pl in PLACEMENTS:
        p = push[tc][pl]
        N["push"][tc][pl] = {k: p[k] for k in ("n", "min", "q1", "median", "q3", "p95", "max")}
        N["pull"][tc][pl] = stats(np.concatenate([fetch_ms(r, tc) for r in runs_B(pl, "seq")]))
        N["baseline"][tc][pl] = stats(np.concatenate([fetch_ms(r, tc) for r in runs_B(pl, "src")]))
write_numbers("spread", N)


def ms(x):
    """Milliseconds below 10 s, seconds above, so that a long stall stands out."""
    return f"{x / 1000:.1f}\\,s" if x >= 10000 else f"{x:,.0f}"


rows = []
for tc in TCS:
    for i, pl in enumerate(PLACEMENTS):
        a, b, c = N["push"][tc][pl], N["pull"][tc][pl], N["baseline"][tc][pl]
        cells = [TCN[tc] if i == 0 else "", NAME[pl],
                 ms(a["min"]), ms(a["median"]), ms(a["p95"]), f"\\textbf{{{ms(a['max'])}}}",
                 ms(b["min"]), ms(b["median"]), ms(b["p95"]), f"\\textbf{{{ms(b['max'])}}}",
                 ms(c["median"]), ms(c["max"])]
        rows.append(" & ".join(cells) + r" \\")
    if tc != TCS[-1]:
        rows.append(r"\addlinespace")
latex = "\n".join([
    "% Generated by analysis/spread.py; do not edit by hand.",
    r"\begin{tabular}{@{}llrrrrrrrrrr@{}}",
    r"\toprule",
    r" & & \multicolumn{4}{c}{\textbf{Push, Set A}} & \multicolumn{4}{c}{\textbf{Pull through EDC, Set B}}"
    r" & \multicolumn{2}{c}{\textbf{Without EDC}} \\",
    r"\cmidrule(lr){3-6}\cmidrule(lr){7-10}\cmidrule(l){11-12}",
    r"\textbf{TC} & \textbf{Placement} & Min & Median & P95 & Max & Min & Median & P95 & Max & Median & Max \\",
    r"\midrule",
    *rows,
    r"\bottomrule",
    r"\end{tabular}",
    ""])
write_table("T5_spread", latex)

if __name__ == "__main__":
    for tc in TCS:
        for pl in PLACEMENTS:
            a, b, c = N["push"][tc][pl], N["pull"][tc][pl], N["baseline"][tc][pl]
            print(f"{tc} {pl:6s} push {a['min']:7.0f} {a['median']:6.0f} {a['p95']:7.0f} {a['max']:7.0f} | "
                  f"pull n={b['n']} {b['min']:5.1f} {b['median']:6.1f} {b['p95']:6.1f} {b['p99']:6.1f} {b['max']:6.0f} | "
                  f"base {c['median']:6.1f} {c['max']:6.0f}")
